package org.bibletranslationtools.orature.e2e

import androidx.compose.foundation.layout.Box
import androidx.compose.ui.graphics.toAwtImage
import androidx.compose.ui.semantics.SemanticsActions
import androidx.compose.ui.test.ComposeUiTest
import androidx.compose.ui.test.ExperimentalTestApi
import androidx.compose.ui.test.SemanticsMatcher
import androidx.compose.ui.test.captureToImage
import androidx.compose.ui.test.isRoot
import androidx.compose.ui.test.performSemanticsAction
import androidx.compose.ui.test.v2.runComposeUiTest
import java.awt.image.BufferedImage
import java.io.File
import javax.imageio.ImageIO
import kotlin.coroutines.EmptyCoroutineContext
import kotlin.time.Duration.Companion.minutes
import kotlinx.coroutines.Dispatchers

/**
 * Runs a Compose UI test the way the recorder's e2e tests do:
 * - effects on [Dispatchers.Main], so LaunchedEffects actually run;
 * - [ComposeUiTest.mainClock] not auto-advancing, so screens that redraw continuously
 *   (waveforms, progress) don't keep waitForIdle from ever returning. [ComposeUiTest.waitUntil]
 *   still advances frames.
 * - the content is cleared before the scene closes, which avoids a navigation teardown race
 *   ("DESTROYED") that otherwise fails a test that passed.
 */
@OptIn(ExperimentalTestApi::class)
internal fun runOratureUiTest(block: suspend ComposeUiTest.() -> Unit) {
    try {
        runComposeUiTest(
            effectContext = Dispatchers.Main,
            runTestContext = EmptyCoroutineContext,
            testTimeout = 15.minutes,
        ) {
            mainClock.autoAdvance = false
            try {
                block()
            } finally {
                runCatching { setContent { Box {} } }
            }
        }
    } catch (e: IllegalStateException) {
        if (e.message?.contains("DESTROYED") != true) throw e
    }
}

/**
 * Records a user journey as numbered, captioned screenshots, so a test run doubles as a
 * picture-by-picture guide to the feature.
 *
 * Each [step] performs its action, then saves a screenshot of the whole window to
 * `build/walkthroughs/<name>/NN-<slug>.png` and appends the caption to that folder's
 * `README.md`. Open the README to read the journey with its pictures.
 */
@OptIn(ExperimentalTestApi::class)
internal class Walkthrough(
    private val test: ComposeUiTest,
    name: String,
    title: String,
    intro: String,
) {
    private val dir = File("build/walkthroughs/$name").apply {
        deleteRecursively()
        mkdirs()
    }
    private val readme = File(dir, "README.md").apply {
        writeText("# $title\n\n$intro\n\nGenerated by the `$name` UI test. Re-run it to refresh these screenshots.\n")
    }
    private var count = 0

    /** Does [action], then screenshots the result under [caption]. */
    suspend fun step(caption: String, action: suspend ComposeUiTest.() -> Unit = {}) {
        test.action()
        snapshot(caption)
    }

    /**
     * Runs the journey, and if it fails, saves a screenshot of where it got stuck before
     * rethrowing, so a failed run shows what was on screen.
     */
    suspend fun run(journey: suspend Walkthrough.() -> Unit) {
        try {
            journey()
        } catch (t: Throwable) {
            runCatching { snapshot("FAILED here: ${t.message?.take(80)}") }
            throw t
        }
    }

    fun snapshot(caption: String) {
        count++
        // Let animations (screen transitions are under a second) finish before drawing.
        repeat(60) { test.mainClock.advanceTimeByFrame() }
        val file = File(dir, "%02d-%s.png".format(count, slug(caption)))
        ImageIO.write(captureWindow(), "png", file)
        readme.appendText("\n## $count. $caption\n\n![$caption](${file.name})\n")
    }

    /**
     * The window as a user sees it. Menus and dialogs are separate roots drawn over the main
     * one, so each root is captured and layered in order at its position in the window.
     */
    private fun captureWindow(): BufferedImage {
        val roots = test.onAllNodes(isRoot())
        val layers = roots.fetchSemanticsNodes().indices.map { i ->
            val node = roots[i]
            val bounds = node.fetchSemanticsNode().boundsInWindow
            Triple(node.captureToImage().toAwtImage(), bounds.left.toInt(), bounds.top.toInt())
        }
        val width = layers.maxOf { (image, x, _) -> x + image.getWidth(null) }
        val height = layers.maxOf { (image, _, y) -> y + image.getHeight(null) }
        return BufferedImage(width, height, BufferedImage.TYPE_INT_ARGB).apply {
            val g = createGraphics()
            layers.forEach { (image, x, y) -> g.drawImage(image, x, y, null) }
            g.dispose()
        }
    }

    private fun slug(text: String) =
        text.lowercase().replace(Regex("[^a-z0-9]+"), "-").trim('-').take(40)
}

/** Waits until a node matching [matcher] is on screen. */
@OptIn(ExperimentalTestApi::class)
internal fun ComposeUiTest.waitFor(matcher: SemanticsMatcher, timeoutMillis: Long = 60_000) {
    waitUntil(timeoutMillis = timeoutMillis) { onAllNodes(matcher).fetchSemanticsNodes().isNotEmpty() }
}

@OptIn(ExperimentalTestApi::class)
internal fun ComposeUiTest.isShowing(matcher: SemanticsMatcher): Boolean =
    onAllNodes(matcher).fetchSemanticsNodes().isNotEmpty()

/**
 * Presses the button (or row) matching [matcher] once it is on screen.
 *
 * This invokes the node's click action directly rather than simulating a mouse press. While
 * narration is recording, the screen updates every frame, and simulated presses on Record and
 * Pause were intermittently dropped (in 1 to 2 of every 3 runs) even once the button had stopped
 * moving. Direct click actions run the same onClick and never missed. Whether a real mouse click
 * can be dropped the same way is worth checking by hand.
 */
@OptIn(ExperimentalTestApi::class)
internal fun ComposeUiTest.tap(matcher: SemanticsMatcher, timeoutMillis: Long = 30_000) {
    waitFor(matcher, timeoutMillis)
    onNode(matcher).performSemanticsAction(SemanticsActions.OnClick)
}
